#!/usr/bin/env node
// VER-07 — ship the WhatsApp UI inside the Worker bundle, not as text bindings.
//
// Why: Cloudflare rejects any single text binding over 5.1 kB (error 10054). The UI JS is
// ~12 kB, so the first live deploy of PR #104 was refused. A Worker ES module has no such
// per-value cap, and bundling the assets also removes a whole class of "page not deployed"
// drift: the UI ships in the same upload as the code that serves it.
//
// The generated module is committed so the Worker import graph stays resolvable offline
// and in tests. `--check` fails when it drifts from public/, exactly like the other
// generated-artifact gates in this repository.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const EDGE_UI_MODULE = 'workers/celia-edge/whatsapp-ui.generated.js';

export const UI_SOURCES = {
  WHATSAPP_UI_HTML: 'public/whatsapp.html',
  WHATSAPP_UI_JS: 'public/whatsapp.js',
  WHATSAPP_UI_CSS: 'public/whatsapp.css',
  WHATSAPP_UI_THEME_CSS: 'public/theme.css',
  WHATSAPP_UI_THEME_JS: 'public/theme.js',
};

export function renderUiModule(assets) {
  const header = [
    '// GENERATED by scripts/build-edge-ui.mjs — do not edit by hand.',
    '// Source of truth: public/. Regenerate with `npm run build:edge-ui`.',
    '// Bundled instead of text bindings because Cloudflare caps a text binding at 5.1 kB (VER-07).',
    '',
  ].join('\n');
  const body = Object.keys(UI_SOURCES)
    .map((name) => `export const ${name} = ${JSON.stringify(assets[name] ?? '')};`)
    .join('\n');
  const map = Object.keys(UI_SOURCES).map((name) => `  ${name}`).join(',\n');
  return `${header}${body}\n\nexport const EDGE_UI = {\n${map}\n};\n`;
}

export async function readUiSources() {
  const entries = await Promise.all(
    Object.entries(UI_SOURCES).map(async ([name, file]) => [name, await readFile(path.join(root, file), 'utf8')])
  );
  return Object.fromEntries(entries);
}

async function main() {
  const expected = renderUiModule(await readUiSources());
  const target = path.join(root, EDGE_UI_MODULE);
  if (process.argv.includes('--check')) {
    const actual = await readFile(target, 'utf8').catch(() => '');
    if (actual !== expected) {
      console.error(`${EDGE_UI_MODULE} is stale. Run: npm run build:edge-ui`);
      process.exit(1);
    }
    console.log(`Edge UI module is current: ${EDGE_UI_MODULE}`);
    return;
  }
  await writeFile(target, expected);
  console.log(`Generated ${EDGE_UI_MODULE} (${expected.length} bytes) from ${Object.keys(UI_SOURCES).length} public assets.`);
}

if (import.meta.url === `file://${process.argv[1]}`) await main();
